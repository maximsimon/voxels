# dataset.py - generate a whole dataset: atlas sets, maps, a registry, and a manifest.
#
# two deliberate choices:
#   - density tiers are STRATIFIED, not sampled per world. a random draw over 12 worlds can
#     hand you 1 dense map or none, and the RL loop picks a random world every episode, so a
#     missing tier is a silently untrained regime. equal counts make the mix reviewable.
#   - every appearance axis is sampled independently per world (ground, sky, atlas set,
#     colors, objects, tiles). bundling them into themes would make every world of a tier
#     look like the same world.

from __future__ import annotations

from pathlib import Path
import pprint

import numpy as np

from .atlas import (ATLAS_SETS, atlas_path, atlas_sets, build_atlas_sets,
                    object_tiles)
from .layouts import DENSITY_TIERS, LAYOUTS, TIER_ORDER, generate_map, plan_layouts, tier_bounds
from .mapgen import MapCanvas
from .palette import COLOR_RGB, EMITTABLE, safe_subsets, objects_for_role
from .registry import world_block, write_registry
from .validate import FILL_TOLERANCE, validate_map, validate_world, report as report_failures

_REPO_ROOT = Path(__file__).resolve().parents[2]
_TEX_DIR = _REPO_ROOT / "core_voxels" / "resources" / "textures"
_GEN_DIR = _REPO_ROOT / "core_voxels" / "resources" / "generated"

GROUND_POOL = ["grass.png", "desert.png", "asphalt.png"]
SKY_POOL = ["stars.png", "sky_clouds.png"]

# a dense world pays its fill target in geometry on every episode switch (the C++ rebuilds the
# world from scratch), so keep the multi-voxel clusters out of it and spend the budget on more
# single-voxel pixels instead
TIER_MAX_VOXELS = {"sparse": None, "medium": None, "dense": 1}


def tier_plan(count: int, tiers: list[str]) -> list[str]:
	"""Interleave `tiers` so a dataset carries equal numbers of each, leftovers to the front."""
	plan = [tiers[i % len(tiers)] for i in range(count)]
	return plan


def split_groups(items: list, groups: int, rng: np.random.Generator) -> list[list]:
	"""Deal `items` into `groups` non-empty lists (shuffled first)."""
	order = list(items)
	rng.shuffle(order)
	groups = max(1, min(groups, len(order)))
	size = len(order) // groups
	out = [order[i * size:(i + 1) * size] for i in range(groups - 1)]
	out.append(order[(groups - 1) * size:])
	return out


def write_manifest(path: str | Path, dataset: str, worlds: list[dict]):
	"""Write an IMPORTABLE python manifest next to the registry.

	A .py rather than JSON so a checker can `import` it, so the file can carry comments, and
	so a regenerated dataset shows up as a readable diff.
	"""
	import os
	rel = os.path.relpath(path, _REPO_ROOT)
	body = pprint.pformat(worlds, indent=1, width=96, sort_dicts=False)
	with open(path, "w") as f:
		f.write(f"# generated by scripts.worldgen - do not edit by hand\n")
		f.write(f"# source: {rel}\n")
		f.write(f"# {len(worlds)} world(s); import this to inspect what a dataset contains\n\n")
		f.write(f"DATASET = {dataset!r}\n\n")
		f.write(f"WORLDS = {body}\n")
	print(f"manifest: wrote {path}")


def _sample_colors(rng: np.random.Generator, minimum: int, maximum: int) -> list[str]:
	"""Draw a conflict-free palette.

	Colors are not independent: getPixelHue gives a pixel to the NEAREST enabled center, so a
	palette is only safe when every color in it still resolves to itself. safe_subsets()
	enumerates those combinations.
	"""
	sizes = [n for n in range(max(1, minimum), min(maximum, _max_palette()) + 1)
	         if safe_subsets(n)]
	if not sizes:
		raise ValueError(f"no conflict-free palette of size {minimum}-{maximum}; "
						 f"largest available is {_max_palette()}")
	size = int(sizes[int(rng.integers(len(sizes)))])
	choices = safe_subsets(size)
	return list(choices[int(rng.integers(len(choices)))])


def _max_palette() -> int:
	sizes = [n for n in range(1, len(EMITTABLE) + 1) if safe_subsets(n)]
	return max(sizes) if sizes else 0


def generate_dataset(name: str, count: int = 12, width: int = 256, height: int = 256,
                     base_seed: int = 0, layouts: list[str] | None = None,
                     density: list[str] | None = None, palette_min: int = 4,
                     palette_max: int = 7, max_layouts: int = 3, atlas_cols: int = 4,
                     atlas_rows: int = 4, ground_pool: list[str] | None = None,
                     sky_pool: list[str] | None = None, atlas_set: str | None = None,
                     spawn_radius: int = 10, validate: bool = True) -> Path:
	"""Generate `count` worlds + <name>.registry + <name>.worlds.py. Returns the registry path.

	Every world gets its own seed (base_seed + index) so one world can be regenerated in
	isolation and every map, palette and texture choice is reproducible from the manifest.
	"""
	out_dir = _GEN_DIR / name
	out_dir.mkdir(parents=True, exist_ok=True)

	layouts = [l for l in (layouts or sorted(LAYOUTS)) if l in LAYOUTS]
	if not layouts:
		raise ValueError(f"no usable layouts in {layouts} - known: {', '.join(LAYOUTS)}")
	tiers = [t for t in (density or TIER_ORDER) if t in DENSITY_TIERS]
	ground_pool = ground_pool or GROUND_POOL
	sky_pool = sky_pool or SKY_POOL

	if atlas_set:
		build_atlas_sets(atlas_cols, atlas_rows, [atlas_set])
	available_sets = atlas_sets()
	if atlas_set and atlas_set not in available_sets:
		raise ValueError(f"unknown atlas set '{atlas_set}' - known: {', '.join(available_sets)}")
	build_atlas_sets(atlas_cols, atlas_rows, available_sets)

	blocks: list[str] = []
	worlds: list[dict] = []
	failures: dict[str, list[str]] = {}

	for i, tier in zip(range(count), tier_plan(count, tiers)):
		seed = base_seed + i
		rng = np.random.default_rng(seed)
		world_name = f"{name}_map{i:03d}"

		lo, hi = tier_bounds(tier)
		target_fill = float(rng.uniform(lo, hi))
		world_layouts = plan_layouts(rng, layouts, max_layouts)
		colors = _sample_colors(rng, max(palette_min, len(world_layouts)), palette_max)
		color_groups = split_groups(colors, len(world_layouts), rng)

		cap = TIER_MAX_VOXELS.get(tier)
		styles: list[list[tuple[str, str]]] = []
		objects: dict[str, str] = {}
		used_objects: set[str] = set()
		for layout_name, group in zip(world_layouts, color_groups):
			group_styles = []
			pool = [o for o in objects_for_role(layout_name, cap) if o not in used_objects] \
				or objects_for_role(layout_name, cap)
			for j, color in enumerate(group):
				obj = pool[j % len(pool)]
				used_objects.add(obj)
				group_styles.append((color, obj))
				objects[color] = obj
			styles.append(group_styles)

		set_name = atlas_set or available_sets[int(rng.integers(len(available_sets)))]
		ground = ground_pool[int(rng.integers(len(ground_pool)))]
		sky = sky_pool[int(rng.integers(len(sky_pool)))]

		mc, layout_report = generate_map(width, height, world_layouts, target_fill, styles,
		                                 seed=seed, spawn_radius=spawn_radius)

		map_rel = f"core_voxels/resources/generated/{name}/{world_name}.png"
		atlas_rel = f"core_voxels/resources/textures/{atlas_path(set_name).name}"
		ground_rel = f"core_voxels/resources/textures/{ground}"
		sky_rel = f"core_voxels/resources/textures/{sky}"

		# one distinct atlas tile per color, so two worlds sharing an atlas set still differ
		capacity = atlas_cols * atlas_rows
		slot_order = rng.permutation(capacity)
		tiles = {color: int(slot_order[j]) for j, color in enumerate(colors)}

		# and one per object as well. A tile per color alone leaves every color of the same
		# object sharing a photo, and the C++ prefers the object's own tile when it has one, so
		# this is what makes a tree look like a tree rather than like whatever the color's
		# slot happened to hold.
		#
		# Only objects reached by exactly ONE color may be declared: an object texture is keyed
		# by object name, so declaring one for an object that several colors map to would
		# override all of their per-color tiles and make those entries dead. Those objects keep
		# the legacy path and take their color's tile, which is what the 2x2 atlases do anyway.
		obj_slots = object_tiles(set_name)
		color_count: dict[str, int] = {}
		for obj in objects.values():
			color_count[obj] = color_count.get(obj, 0) + 1
		object_textures = {obj: obj_slots[obj] for obj in sorted(color_count)
		                   if color_count[obj] == 1 and obj in obj_slots}

		meta = dict(name=world_name, seed=seed, map=map_rel, atlas=atlas_rel,
		            ground=ground_rel, sky=sky_rel, atlas_cols=atlas_cols,
		            atlas_rows=atlas_rows, atlas_set=set_name, colors=colors, tiles=tiles,
		            objects=objects, object_textures=object_textures,
		            layouts=world_layouts,
		            density_tier=tier, target_fill=round(target_fill, 4),
		            fill=round(mc.fill_fraction(), 4))

		if validate:
			mc.save_png(out_dir / f"{world_name}.png")
			problems = validate_map(mc, tier=tier, target_fill=target_fill, colors=colors,
			                        layouts=world_layouts)
			problems += validate_world(meta, mc, _REPO_ROOT)
			if problems:
				failures[world_name] = problems
		else:
			mc.save_png(out_dir / f"{world_name}.png")

		blocks.append(world_block(
			name=world_name, map_path=map_rel, atlas_path=atlas_rel,
			ground_path=ground_rel, sky_path=sky_rel,
			atlas_cols=atlas_cols, atlas_rows=atlas_rows,
			colors=colors, tiles=tiles, objects=objects,
			object_textures=object_textures))

		worlds.append(dict(meta, layout_report=layout_report))

	registry_path = out_dir / f"{name}.registry"
	write_registry(registry_path, blocks)
	write_manifest(out_dir / f"{name}.worlds.py", name, worlds)

	print(f"\ndataset '{name}': {count} world(s) in {out_dir}")
	for tier in TIER_ORDER:
		fills = [w["fill"] for w in worlds if w["density_tier"] == tier]
		if fills:
			lo, hi = tier_bounds(tier)
			print(f"  {tier:<7} {len(fills):>2} world(s)  band {lo:.0%}-{hi:.0%}  "
				  f"actual {min(fills):.1%}-{max(fills):.1%}")
	combos = sorted({tuple(w["layouts"]) for w in worlds})
	print(f"  layout combinations used: {len(combos)}")
	for c in combos:
		print(f"    {'+'.join(c)}")

	if failures:
		print()
		report_failures(failures)
		raise SystemExit(f"dataset '{name}' rejected: {len(failures)} world(s) failed validation")
	print("validate: all worlds OK")

	return registry_path